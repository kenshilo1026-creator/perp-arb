fn rest_binds_full_identity_and_partial_cancel() {
    let r = intent().request(client().scope()).unwrap();
    let mut v = response();
    assert_eq!(
        events::rest(&r, &v, Instant::now())
            .unwrap()
            .found
            .order
            .cumulative,
        number("1").unwrap()
    );
    for key in ["symbol", "orderId", "origQty", "side", "clientOrderId"] {
        let mut wrong = v.clone();
        wrong[key] = Value::Null;
        assert!(events::rest(&r, &wrong, Instant::now()).is_err(), "{key}");
    }
    v["status"] = json!("CANCELED");
    v["origClientOrderId"] = json!("pa1");
    v["clientOrderId"] = json!("cancel-id");
    let e = events::rest(&r, &v, Instant::now()).unwrap();
    assert_eq!(e.found.order.status, Status::Canceled);
    assert_eq!(e.found.order.cumulative, number("1").unwrap());
}
