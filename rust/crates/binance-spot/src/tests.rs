static SEQUENCE: AtomicU64 = AtomicU64::new(0);
struct Temp(PathBuf);
impl Temp {
    fn new() -> Self {
        Self(std::env::temp_dir().join(format!(
            "pa-binance-{}-{}.jsonl",
            std::process::id(),
            SEQUENCE.fetch_add(1, Ordering::Relaxed)
        )))
    }
}
impl Drop for Temp {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

#[test]
fn hmac_canonical_wire_and_secret_redaction() {
    let c = creds();
    let p = BTreeMap::from([
        ("timestamp".into(), "100".into()),
        ("symbol".into(), "ETHUSDT".into()),
    ]);
    let wire = auth::canonical(&p).unwrap();
    assert_eq!(wire, "symbol=ETHUSDT&timestamp=100");
    // Independently generated by Python hashlib/hmac with these public fixture values.
    assert_eq!(
        c.sign(&wire),
        "70712a17cd5756b645ba5c630971a2fe3c4e608e21f2589107bfde008deaf26e"
    );
    assert!(auth::canonical(&BTreeMap::from([("x".into(), "a&b=secret".into())])).is_err());
    assert!(auth::Credentials::new("x", "y").is_err());
    let e = Error::Api {
        status: 400,
        code: Some(-1022),
    }
    .to_string();
    assert!(!e.contains('K'));
    assert!(!e.contains("signature="));
}
