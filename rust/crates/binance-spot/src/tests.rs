// Each exchange stub accepts a bounded, explicit script. No external network.
async fn server(
    replies: Vec<(u16, Value, &'static str, Duration)>,
) -> (String, tokio::task::JoinHandle<Vec<String>>) {
    let listener = TcpListener::bind("127.0.0.1:0").await.unwrap();
    let addr = listener.local_addr().unwrap();
    let task = tokio::spawn(async move {
        let mut requests = Vec::new();
        for (status, body, extra, delay) in replies {
            let (mut socket, _) = tokio::time::timeout(Duration::from_secs(3), listener.accept())
                .await
                .unwrap()
                .unwrap();
            let mut bytes = Vec::new();
            let mut buf = [0u8; 1024];
            while !bytes.ends_with(b"\r\n\r\n") {
                let n = socket.read(&mut buf).await.unwrap();
                if n == 0 {
                    break;
                }
                bytes.extend_from_slice(&buf[..n]);
                assert!(bytes.len() < 20000);
            }
            requests.push(String::from_utf8(bytes).unwrap());
            tokio::time::sleep(delay).await;
            let body = body.to_string();
            let wire=format!("HTTP/1.1 {status} Test\r\nContent-Length: {}\r\nContent-Type: application/json\r\nConnection: close\r\n{extra}\r\n{body}",body.len());
            let _ = socket.write_all(wire.as_bytes()).await;
        }
        requests
    });
    (format!("http://{addr}"), task)
}
fn time_reply() -> (u16, Value, &'static str, Duration) {
    (200, json!({"serverTime":wall_ms()}), "", Duration::ZERO)
}
#[tokio::test]
async fn signed_post_exact_bytes_single_attempt_and_lookup() {
    let (base, task) = server(vec![
        time_reply(),
        (200, response(), "", Duration::ZERO),
        (200, response(), "", Duration::ZERO),
    ])
    .await;
    let c = client::Client::fixture(creds(), base, String::new(), Duration::from_secs(2)).unwrap();
    c.sync_time().await.unwrap();
    let path = Temp::new();
    let mut j = journal::Journal::create(&path.0, c.scope(), intent()).unwrap();
    let e = c.submit(j.prepare_dispatch().unwrap()).await.unwrap();
    j.observe(e).unwrap();
    assert!(matches!(
        c.submit_once(&intent()).await,
        Err(Error::AlreadySubmitted)
    ));
    assert!(c.query(&j.request().unwrap()).await.unwrap().is_some());
    let requests = task.await.unwrap();
    let first = requests[1].lines().next().unwrap();
    assert!(first.starts_with("POST /api/v3/order?"));
    let query = first.split('?').nth(1).unwrap().split(' ').next().unwrap();
    let (payload, signature) = query.rsplit_once("&signature=").unwrap();
    assert_eq!(creds().sign(payload), signature);
    assert!(payload.contains("type=MARKET"));
    assert!(!payload.contains("price="));
}
