#[tokio::test]
async fn coordinator_ws_fill_is_not_erased_by_late_rest_and_recovery_is_explicit() {
    let mut filled = response();
    filled["executedQty"] = json!("2");
    filled["cummulativeQuoteQty"] = json!("200");
    filled["status"] = json!("FILLED");
    filled["updateTime"] = json!(101);
    let (base, server) = server(vec![
        time_reply(),
        (200, response(), "", Duration::from_millis(100)),
        (200, filled, "", Duration::ZERO),
    ])
    .await;
    let c = client::Client::fixture(creds(), base, String::new(), Duration::from_secs(2)).unwrap();
    c.sync_time().await.unwrap();
    let (actor, worker) = perp_arb_private_events::actor::channel(c.scope(), 10, 10).unwrap();
    let task = worker.spawn();
    let session = actor.connected().await.unwrap();
    let request = intent().request(c.scope()).unwrap();
    let events::Event::Order(first) =
        events::stream(&c.scope(), 0, &report(), Instant::now()).unwrap()
    else {
        panic!()
    };
    let one = coordination::observe_ws(&actor, session.clone(), &request, *first.clone())
        .await
        .unwrap();
    let duplicate = coordination::observe_ws(&actor, session.clone(), &request, *first)
        .await
        .unwrap();
    assert_eq!(one.cumulative, duplicate.cumulative);
    let mut by_id = request.clone();
    by_id.selector = Selector::OrderId("42".into());
    let query = {
        let (c, actor, r) = (c.clone(), actor.clone(), by_id.clone());
        tokio::spawn(async move { coordination::reconcile(&c, &actor, &r).await })
    };
    tokio::time::sleep(Duration::from_millis(40)).await;
    let mut ws = report();
    ws["event"]["z"] = json!("2");
    ws["event"]["Z"] = json!("200");
    ws["event"]["X"] = json!("FILLED");
    ws["event"]["t"] = json!(8);
    ws["event"]["T"] = json!(101);
    let events::Event::Order(e) = events::stream(&c.scope(), 0, &ws, Instant::now()).unwrap()
    else {
        panic!()
    };
    coordination::observe_ws(&actor, session.clone(), &request, *e)
        .await
        .unwrap();
    let stale = query.await.unwrap().unwrap().unwrap();
    assert_eq!(stale.cumulative, number("2").unwrap());
    assert_eq!(stale.status, Status::Filled);
    assert!(stale.requires_reconciliation);
    let current = coordination::reconcile(&c, &actor, &by_id)
        .await
        .unwrap()
        .unwrap();
    assert_eq!(current.cumulative, number("2").unwrap());
    assert!(!current.requires_reconciliation);
    actor.disconnected(session).await.unwrap();
    assert!(!actor.health().connected);
    assert!(actor.snapshots().await.unwrap()[0].requires_reconciliation);
    actor.shutdown().await.unwrap();
    task.await.unwrap();
    server.await.unwrap();
}

